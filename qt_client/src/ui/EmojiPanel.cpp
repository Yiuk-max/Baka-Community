// ---------- 实现 ----------
EmojiPanel::EmojiPanel(QWidget *parent)
    : QFrame(parent, Qt::Popup | Qt::FramelessWindowHint | Qt::NoDropShadowWindowHint)
{
    setObjectName("emojiPanel");
    setAttribute(Qt::WA_TranslucentBackground);   // 圆角外面透明，否则四个角是黑的
    setFixedSize(420, 360);

    auto *mainLayout = new QVBoxLayout(this);
    mainLayout->setContentsMargins(9, 9, 9, 9);   // 8px 内边距 + 1px 边框
    mainLayout->setSpacing(6);

    // 分类标签行（下面一条分隔线，画在 QSS 里）
    auto *tabRow    = new QFrame(this);
    tabRow->setObjectName("emojiTabRow");
    auto *tabLayout = new QHBoxLayout(tabRow);
    tabLayout->setContentsMargins(0, 0, 0, 7);
    tabLayout->setSpacing(2);
    const auto &cats = categories();
    for (int i = 0; i < cats.size(); ++i) {
        auto *btn = new QPushButton(cats[i].icon, tabRow);
        btn->setObjectName("emojiTab");
        btn->setFixedSize(32, 32);
        btn->setCheckable(true);
        btn->setCursor(Qt::PointingHandCursor);
        btn->setFocusPolicy(Qt::NoFocus);
        btn->setToolTip(cats[i].name);
        connect(btn, &QPushButton::clicked, this, [this, i] { showCategory(i); });
        tabLayout->addWidget(btn);
        m_tabs.append(btn);
    }
    tabLayout->addStretch();
    mainLayout->addWidget(tabRow);

    // 每个分类一页；这里只建空的滚动区，按钮等第一次切到该分类再建（见 fillPage）
    m_stack = new QStackedWidget(this);
    for (int i = 0; i < cats.size(); ++i) {
        auto *scroll = new QScrollArea(m_stack);
        scroll->setObjectName("emojiScroll");
        scroll->setFrameShape(QFrame::NoFrame);
        scroll->setWidgetResizable(true);
        scroll->setHorizontalScrollBarPolicy(Qt::ScrollBarAlwaysOff);
        m_pages.append(scroll);
        m_stack->addWidget(scroll);
    }
    mainLayout->addWidget(m_stack, 1);

    showCategory(0);
}

void EmojiPanel::fillPage(int idx) {
    QScrollArea *scroll = m_pages[idx];
    if (scroll->widget()) return;

    const int cols = 8;
    auto *container = new QWidget;
    container->setObjectName("emojiGrid");
    auto *grid = new QGridLayout(container);
    grid->setContentsMargins(0, 0, 0, 0);
    grid->setSpacing(2);
    for (int c = 0; c < cols; ++c) grid->setColumnStretch(c, 1);

    int row = 0, col = 0;
    for (const QString &emoji : categories()[idx].emojis) {
        auto *btn = new QPushButton(emoji, container);
        btn->setObjectName("emojiButton");
        btn->setFixedHeight(38);
        btn->setSizePolicy(QSizePolicy::Ignored, QSizePolicy::Fixed);   // 8 列平分宽度
        btn->setCursor(Qt::PointingHandCursor);
        btn->setFocusPolicy(Qt::NoFocus);
        connect(btn, &QPushButton::clicked, this, [this, emoji] { emit emojiSelected(emoji); });
        grid->addWidget(btn, row, col);
        if (++col >= cols) { col = 0; ++row; }
    }
    grid->setRowStretch(row + 1, 1);   // 表情少的分类：行靠上，不被拉开
    scroll->setWidget(container);
}

void EmojiPanel::showCategory(int idx) {
    fillPage(idx);
    for (int i = 0; i < m_tabs.size(); ++i)
        m_tabs[i]->setChecked(i == idx);
    m_stack->setCurrentIndex(idx);
}

void EmojiPanel::popup(const QRect &anchorGlobal) {
    m_anchor = anchorGlobal;
    setAttribute(Qt::WA_NoMouseReplay, false);

    int x = anchorGlobal.right() + 1 - width();
    int y = anchorGlobal.top() - height() - 8;//让面板显示在按钮上方，并留出 8px 间距
    if (QScreen *screen = QGuiApplication::screenAt(anchorGlobal.center())) {
        const QRect sg = screen->availableGeometry();
        x = qBound(sg.left() + 8, x, qMax(sg.left() + 8, sg.right() - width() - 7));//把一个数限制在指定范围内，qBound(最小X, 原始X, 最大X)
        if (y < sg.top() + 8)
            y = qMin(anchorGlobal.bottom() + 9, sg.bottom() - height() - 7);
    }
    move(x, y);
    show();
}

void EmojiPanel::mousePressEvent(QMouseEvent *event) {
    // 面板开着时再点表情按钮：只关面板，不把这次点击转给按钮（否则刚关又被打开）
    if (!rect().contains(event->position().toPoint())
            && m_anchor.contains(event->globalPosition().toPoint()))
        setAttribute(Qt::WA_NoMouseReplay);
    QFrame::mousePressEvent(event);
}
